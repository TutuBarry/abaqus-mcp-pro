class TestSaveReport:
    def test_save_to_file(self, tmp_path):
        c = CapsuleEntry(capsule_id="test", job_name="Job-1", job_status="COMPLETED")
        r = SimulationReport(capsule=c)
        path = str(tmp_path / "report.md")
        saved = save_report(r, path)
        assert saved == str(Path(path).resolve())
        assert Path(path).exists()
        content = Path(path).read_text(encoding="utf-8")
        assert "Abaqus Simulation Report" in content
        assert "Job-1" in content

    def test_save_creates_directory(self, tmp_path):
        r = SimulationReport()
        path = str(tmp_path / "subdir" / "report.md")
        save_report(r, path)
        assert Path(path).exists()

    def test_save_full_report(self, tmp_path):
        capsule = CapsuleEntry(capsule_id="test", job_name="Job-1", job_status="COMPLETED")
        kpi = KPILensReport(odb_path="/tmp/test.odb")
        kpi.add_result(KPIResult(query_id="max_stress", value=345.6))
        ct = ContractReport()
        ct.add_result(ContractResult(contract_id="c1", kpi_name="stress", passed=True, actual=345.0, expected_display="[0, 500]", message="OK"))
        diag = DiagnosisReport(job_name="test", workdir="/tmp")
        r = SimulationReport(
            capsule=capsule, kpi_lens=kpi, contracts=ct, diagnosis=diag,
            screenshots=["/tmp/shot.png"],
        )
        path = str(tmp_path / "full_report.md")
        save_report(r, path)
        content = Path(path).read_text(encoding="utf-8")
        assert "Model & Job Summary" in content
        assert "KPI Lens Results" in content
        assert "Physics Contracts" in content
        assert "Solver Diagnosis" in content
        assert "Screenshots" in content
        assert "Report generated by abaqus-mcp-pro" in content
