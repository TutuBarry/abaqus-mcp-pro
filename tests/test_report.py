class TestFormatReportCompact:
    def test_empty(self):
        r = SimulationReport()
        compact = format_report_compact(r)
        assert "Report:" in compact

    def test_with_capsule(self):
        c = CapsuleEntry(capsule_id="test", job_name="Job-1", job_status="COMPLETED")
        r = SimulationReport(capsule=c)
        compact = format_report_compact(r)
        assert "test" in compact
        assert "Job-1" in compact
        assert "COMPLETED" in compact

    def test_with_all(self):
        capsule = CapsuleEntry(capsule_id="test", job_name="Job-1", job_status="COMPLETED")
        kpi = KPILensReport(odb_path="/tmp/test.odb")
        kpi.add_result(KPIResult(query_id="q1", value=100.0))
        ct = ContractReport()
        ct.add_result(ContractResult(contract_id="c1", kpi_name="s", passed=True, message="OK"))
        diag = DiagnosisReport(job_name="test", workdir="/tmp")
        diag.add_event(DiagnosticEvent(
            category="general", severity="info", pattern_id="done",
            file="x.log", line=1, raw_line="done", suggestion="ok",
        ))
        sf = SilentFailureReport(model_name="test")
        sf.add_finding(SilentFailureFinding(
            category="mesh_integrity", severity="error", check_id="mesh_zero",
            passed=False, detail="No elements",
        ))
        r = SimulationReport(
            capsule=capsule, kpi_lens=kpi, contracts=ct, diagnosis=diag,
            silent_failures=sf,
            screenshots=["/tmp/shot.png"],
        )
        compact = format_report_compact(r)
        assert "Capsule: test" in compact
        assert "KPI Lens: 1 OK" in compact
        assert "Contracts: 1 passed" in compact
        assert "Diagnosis: 0 errors" in compact
        assert "Silent Failures: 1 failed" in compact
        assert "Screenshots: 1" in compact


