class TestSimulationReport:
    def test_defaults(self):
        r = SimulationReport()
        assert r.title == "Abaqus Simulation Report"
        assert r.generated_at != ""
        assert r.capsule is None
        assert r.kpi_lens is None
        assert r.contracts is None
        assert r.diagnosis is None
        assert r.silent_failures is None
        assert r.screenshots == []
        assert r.extra_sections == {}

    def test_custom_title(self):
        r = SimulationReport(title="My Custom Report")
        assert r.title == "My Custom Report"

    def test_with_capsule(self):
        c = CapsuleEntry(capsule_id="test")
        r = SimulationReport(capsule=c)
        assert r.capsule is c

    def test_with_all_sections(self):
        capsule = CapsuleEntry(capsule_id="test")
        kpi = KPILensReport(odb_path="/tmp/test.odb")
        contracts = ContractReport()
        diagnosis = DiagnosisReport(job_name="test", workdir="/tmp")
        sf = SilentFailureReport(model_name="test")
        r = SimulationReport(
            capsule=capsule, kpi_lens=kpi, contracts=contracts, diagnosis=diagnosis,
            silent_failures=sf,
            screenshots=["/tmp/shot.png"],
            extra_sections={"Notes": "Some custom notes."},
        )
        assert r.capsule is capsule
        assert r.kpi_lens is kpi
        assert r.contracts is contracts
        assert r.diagnosis is diagnosis
        assert r.silent_failures is sf
        assert len(r.screenshots) == 1
        assert "Notes" in r.extra_sections


